import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import '../models/case_record.dart';

class PdfService {
  static Future<pw.Document> generateCasePdf(
    CaseRecord record, {
    required int caseNumber,
  }) async {
    final isUrdu = record.isUrdu;

    pw.Font baseFont;
    pw.Font boldFont;

    try {
      baseFont = isUrdu
          ? await PdfGoogleFonts.notoNastaliqUrduRegular()
          : await PdfGoogleFonts.interRegular();
      boldFont = isUrdu
          ? await PdfGoogleFonts.notoNastaliqUrduBold()
          : await PdfGoogleFonts.interBold();
    } catch (_) {
      baseFont = pw.Font.helvetica();
      boldFont = pw.Font.helveticaBold();
    }

    final doc = pw.Document(
      theme: pw.ThemeData.withFont(base: baseFont, bold: boldFont, boldItalic: boldFont),
    );

    final dateStr = _formatDate(record.savedAt);
    final textDir = isUrdu ? pw.TextDirection.rtl : pw.TextDirection.ltr;

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        textDirection: textDir,
        margin: const pw.EdgeInsets.symmetric(horizontal: 50, vertical: 48),
        header: (ctx) => _buildHeader(caseNumber),
        footer: (ctx) => _buildFooter(ctx, dateStr),
        build: (ctx) => [
          pw.SizedBox(height: 12),
          if (record.heading.isNotEmpty)
            pw.Directionality(
              textDirection: textDir,
              child: pw.Text(
                record.heading,
                textDirection: textDir,
                style: pw.TextStyle(fontSize: 24, fontWeight: pw.FontWeight.bold, color: const PdfColor.fromInt(0xFF0A1929)),
              ),
            ),
          pw.SizedBox(height: 16),
          pw.Container(height: 1.5, decoration: const pw.BoxDecoration(color: PdfColor.fromInt(0xFF3399FF))),
          pw.SizedBox(height: 20),
          if (record.details.isNotEmpty)
            pw.Directionality(
              textDirection: textDir,
              child: pw.Text(
                record.details,
                textDirection: textDir,
                style: const pw.TextStyle(fontSize: 12, color: PdfColor.fromInt(0xFF1A1A1A), lineSpacing: 6),
              ),
            ),
          pw.SizedBox(height: 32),
          pw.Align(
            alignment: pw.Alignment.centerRight,
            child: pw.Text(dateStr, style: pw.TextStyle(fontSize: 9, color: const PdfColor.fromInt(0xFF9AA5B4), fontStyle: pw.FontStyle.normal)),
          ),
        ],
      ),
    );
    return doc;
  }

  static pw.Widget _buildHeader(int caseNumber) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Row(mainAxisAlignment: pw.MainAxisAlignment.spaceBetween, children: [
          pw.Text('POLICE CASE DOCUMENTATION',
              style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold, color: const PdfColor.fromInt(0xFF0A1929), letterSpacing: 1.5)),
          pw.Container(
            padding: const pw.EdgeInsets.symmetric(horizontal: 12, vertical: 4),
            decoration: pw.BoxDecoration(color: const PdfColor.fromInt(0xFFF0F4F8), borderRadius: pw.BorderRadius.circular(4)),
            child: pw.Text('Case #$caseNumber',
                style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold, color: const PdfColor.fromInt(0xFF3399FF))),
          ),
        ]),
        pw.SizedBox(height: 10),
        pw.Container(height: 0.5, color: const PdfColor.fromInt(0xFFDDDDDD)),
      ],
    );
  }

  static pw.Widget _buildFooter(pw.Context ctx, String dateStr) {
    return pw.Column(children: [
      pw.Container(height: 0.5, color: const PdfColor.fromInt(0xFFDDDDDD)),
      pw.SizedBox(height: 8),
      pw.Row(mainAxisAlignment: pw.MainAxisAlignment.spaceBetween, children: [
        pw.Text('Generated by Police Case Docs', style: const pw.TextStyle(fontSize: 8, color: PdfColor.fromInt(0xFF9AA5B4))),
        pw.Text('Page ${ctx.pageNumber} of ${ctx.pagesCount}', style: const pw.TextStyle(fontSize: 8, color: PdfColor.fromInt(0xFF9AA5B4))),
      ]),
    ]);
  }

  static String _formatDate(DateTime dt) {
    final days = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];
    final months = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
    final h = dt.hour > 12 ? dt.hour - 12 : (dt.hour == 0 ? 12 : dt.hour);
    final ampm = dt.hour >= 12 ? 'PM' : 'AM';
    final min = dt.minute.toString().padLeft(2, '0');
    return '${days[dt.weekday - 1]}, ${months[dt.month - 1]} ${dt.day}, ${dt.year} at $h:$min $ampm';
  }
}
